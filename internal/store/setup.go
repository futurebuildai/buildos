// CreateTradeCategoryParams is the input for inserting a trade category.
type CreateTradeCategoryParams struct {
	OrgID       uuid.UUID
	Code        string
	Name        string
	Description *string
	IsDefault   bool
}

// CreateTradeCategory inserts a row. UNIQUE(org_id, code) means a
// duplicate code returns a pgx unique-violation error — the service
// is expected to either upsert or pre-check.
func (s *SetupStore) CreateTradeCategory(ctx context.Context, tx pgx.Tx, p CreateTradeCategoryParams) (models.TradeCategory, error) {
	var t models.TradeCategory
	err := tx.QueryRow(ctx, `
		INSERT INTO trade_categories (org_id, code, name, description, is_default)
		VALUES ($1, $2, $3, $4, $5)
		RETURNING id, org_id, code, name, description, is_default, created_at, updated_at`,
		p.OrgID, p.Code, p.Name, p.Description, p.IsDefault,
	).Scan(&t.ID, &t.OrgID, &t.Code, &t.Name, &t.Description, &t.IsDefault, &t.CreatedAt, &t.UpdatedAt)
	if err != nil {
		return models.TradeCategory{}, fmt.Errorf("insert trade category: %w", err)
	}
	return t, nil
}

// ListTradeCategories returns all trade categories for an org, ordered
// by is_default DESC, name ASC. Defaults float to the top of the
// wizard's review screen so operators see the seeded set first.
func (s *SetupStore) ListTradeCategories(ctx context.Context, tx pgx.Tx, orgID uuid.UUID) ([]models.TradeCategory, error) {
	rows, err := tx.Query(ctx, `
		SELECT id, org_id, code, name, description, is_default, created_at, updated_at
		FROM trade_categories
		WHERE org_id = $1
		ORDER BY is_default DESC, name ASC`, orgID)
	if err != nil {
		return nil, fmt.Errorf("list trade categories: %w", err)
	}
	defer rows.Close()

	var out []models.TradeCategory
	for rows.Next() {
		var t models.TradeCategory
		if err := rows.Scan(&t.ID, &t.OrgID, &t.Code, &t.Name, &t.Description, &t.IsDefault, &t.CreatedAt, &t.UpdatedAt); err != nil {
			return nil, fmt.Errorf("scan trade category: %w", err)
		}
		out = append(out, t)
	}
	return out, rows.Err()
}

