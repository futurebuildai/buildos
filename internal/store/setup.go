// ---------- permit_jurisdictions ----------

// CreatePermitJurisdictionParams is the input for inserting a permit
// jurisdiction. PermitTypes and InspectionChecklist are raw JSONB
// (passed through without re-marshaling); empty slices land as
// '[]'::jsonb via the schema default.
type CreatePermitJurisdictionParams struct {
	OrgID               uuid.UUID
	Name                string
	Region              *string
	PermitTypes         []byte // raw JSONB; pass nil for the schema default
	InspectionChecklist []byte // raw JSONB; pass nil for the schema default
	Notes               *string
}

// CreatePermitJurisdiction inserts a row.
func (s *SetupStore) CreatePermitJurisdiction(ctx context.Context, tx pgx.Tx, p CreatePermitJurisdictionParams) (models.PermitJurisdiction, error) {
	// When the caller passes nil for the JSONB columns, fall back to
	// '[]' so the SQL parameter type is unambiguous (pgx infers []byte
	// = JSONB; nil bytes = NULL which the NOT NULL column rejects).
	permitTypes := p.PermitTypes
	if permitTypes == nil {
		permitTypes = []byte("[]")
	}
	checklist := p.InspectionChecklist
	if checklist == nil {
		checklist = []byte("[]")
	}

	var j models.PermitJurisdiction
	err := tx.QueryRow(ctx, `
		INSERT INTO permit_jurisdictions (org_id, name, region, permit_types, inspection_checklist, notes)
		VALUES ($1, $2, $3, $4, $5, $6)
		RETURNING id, org_id, name, region, permit_types, inspection_checklist, notes, created_at, updated_at`,
		p.OrgID, p.Name, p.Region, permitTypes, checklist, p.Notes,
	).Scan(&j.ID, &j.OrgID, &j.Name, &j.Region, &j.PermitTypes, &j.InspectionChecklist, &j.Notes, &j.CreatedAt, &j.UpdatedAt)
	if err != nil {
		return models.PermitJurisdiction{}, fmt.Errorf("insert permit jurisdiction: %w", err)
	}
	return j, nil
}

// ListPermitJurisdictions returns all permit jurisdictions for an org,
