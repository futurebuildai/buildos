// SetupStore manages the rows the onboarding wizard reads + writes:
//   - organizations company-profile columns (migration 010 extension)
//   - setup_bootstrap_tokens
//   - trade_categories
//   - cost_codes
//   - working_calendars + holiday_overrides
//   - permit_jurisdictions
//
// All methods take a pgx.Tx so the service layer can compose wizard
// steps inside one transaction with the audit-log write (matches the
// pattern in schedule.go, a2a.go).
type SetupStore struct{}

// NewSetupStore constructs a SetupStore. Stateless — safe to share.
func NewSetupStore() *SetupStore { return &SetupStore{} }

// ---------- organizations company profile ----------

// UpdateCompanyProfileParams is the input for the wizard's step-1
// company-info submission. Every field is optional at the SQL level
// (matches the migration's nullable columns); the service is expected
// to enforce step-completion invariants (e.g., LegalName + Region
// required) before calling.
type UpdateCompanyProfileParams struct {
	OrgID       uuid.UUID
	LegalName   *string
	Address     *string
	EIN         *string
	CompanyType *string
	Region      *string
}

// UpdateCompanyProfile writes the org-level company-info fields.
// COALESCE allows the wizard to PATCH individual fields without losing
// values from a prior submission — useful when the wizard is resumed
// after a partial submit.
func (s *SetupStore) UpdateCompanyProfile(ctx context.Context, tx pgx.Tx, p UpdateCompanyProfileParams) error {
	cmd, err := tx.Exec(ctx, `
		UPDATE organizations SET
			legal_name   = COALESCE($2, legal_name),
			address      = COALESCE($3, address),
			ein          = COALESCE($4, ein),
			company_type = COALESCE($5, company_type),
			region       = COALESCE($6, region),
			updated_at   = now()
		WHERE id = $1`,
		p.OrgID, p.LegalName, p.Address, p.EIN, p.CompanyType, p.Region,
	)
	if err != nil {
		return fmt.Errorf("update company profile: %w", err)
	}
	if cmd.RowsAffected() == 0 {
		return ErrNotFound
	}
	return nil
}

// GetCompanyProfile reads the org-level company-info fields plus the
// onboarding gate state. Used by GET /setup/state to render the
// wizard's current progress.
func (s *SetupStore) GetCompanyProfile(ctx context.Context, tx pgx.Tx, orgID uuid.UUID) (models.CompanyProfile, error) {
	var cp models.CompanyProfile
	err := tx.QueryRow(ctx, `
		SELECT legal_name, address, ein, company_type, region,
		       onboarding_complete, onboarding_completed_at
		FROM organizations
		WHERE id = $1`, orgID,
	).Scan(
		&cp.LegalName, &cp.Address, &cp.EIN, &cp.CompanyType, &cp.Region,
		&cp.OnboardingComplete, &cp.OnboardingCompletedAt,
	)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return models.CompanyProfile{}, ErrNotFound
		}
		return models.CompanyProfile{}, fmt.Errorf("get company profile: %w", err)
	}
	return cp, nil
}

// CompleteOnboarding flips onboarding_complete=true and stamps the
// completion time. Idempotent — calling twice is a no-op on the second
// call (completed_at is not advanced). Returns ErrNotFound if the org
// row is missing.
func (s *SetupStore) CompleteOnboarding(ctx context.Context, tx pgx.Tx, orgID uuid.UUID, now time.Time) error {
	cmd, err := tx.Exec(ctx, `
		UPDATE organizations SET
			onboarding_complete      = true,
			onboarding_completed_at  = COALESCE(onboarding_completed_at, $2),
			updated_at               = now()
		WHERE id = $1`, orgID, now)
	if err != nil {
		return fmt.Errorf("complete onboarding: %w", err)
	}
	if cmd.RowsAffected() == 0 {
		return ErrNotFound
	}
	return nil
}

// ---------- setup_bootstrap_tokens ----------

// CreateBootstrapTokenParams stores a pre-hashed token. The cleartext
// token is generated by the caller and shown ONCE in fork.yaml; only
// the hash lands in the DB.
type CreateBootstrapTokenParams struct {
	OrgID     uuid.UUID
	TokenHash string
	ExpiresAt time.Time
}

// CreateBootstrapToken persists a one-shot bootstrap token. The unique
// index on token_hash means a hash collision is a constraint violation
// — extremely unlikely with argon2id but surface as a generic error.
func (s *SetupStore) CreateBootstrapToken(ctx context.Context, tx pgx.Tx, p CreateBootstrapTokenParams) (uuid.UUID, error) {
	var id uuid.UUID
	err := tx.QueryRow(ctx, `
		INSERT INTO setup_bootstrap_tokens (org_id, token_hash, expires_at)
		VALUES ($1, $2, $3)
		RETURNING id`, p.OrgID, p.TokenHash, p.ExpiresAt,
	).Scan(&id)
	if err != nil {
		return uuid.Nil, fmt.Errorf("insert bootstrap token: %w", err)
	}
	return id, nil
}

// GetActiveBootstrapTokenByHash looks up an unredeemed, unexpired token
// by its hash. Returns ErrNotFound when no row matches, even if the
// token exists but is redeemed or expired — the service layer never
// needs to distinguish those cases.
func (s *SetupStore) GetActiveBootstrapTokenByHash(ctx context.Context, tx pgx.Tx, hash string, now time.Time) (models.SetupBootstrapToken, error) {
	var t models.SetupBootstrapToken
	err := tx.QueryRow(ctx, `
		SELECT id, org_id, token_hash, issued_at, expires_at, redeemed_at, redeemed_by
		FROM setup_bootstrap_tokens
		WHERE token_hash = $1
		  AND redeemed_at IS NULL
		  AND expires_at > $2`, hash, now,
	).Scan(&t.ID, &t.OrgID, &t.TokenHash, &t.IssuedAt, &t.ExpiresAt, &t.RedeemedAt, &t.RedeemedBy)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return models.SetupBootstrapToken{}, ErrNotFound
		}
		return models.SetupBootstrapToken{}, fmt.Errorf("get bootstrap token: %w", err)
	}
	return t, nil
}

// RedeemBootstrapToken marks a token redeemed. The WHERE clause double-
// checks redeemed_at IS NULL so a concurrent redemption attempt (two
// admins racing on the same token) sees RowsAffected=0 and the service
// layer rolls back rather than minting a second owner.
func (s *SetupStore) RedeemBootstrapToken(ctx context.Context, tx pgx.Tx, tokenID, redeemedBy uuid.UUID, now time.Time) error {
	cmd, err := tx.Exec(ctx, `
		UPDATE setup_bootstrap_tokens SET
			redeemed_at = $2,
			redeemed_by = $3
		WHERE id = $1
		  AND redeemed_at IS NULL`, tokenID, now, redeemedBy)
	if err != nil {
		return fmt.Errorf("redeem bootstrap token: %w", err)
	}
	if cmd.RowsAffected() == 0 {
		return ErrNotFound
	}
	return nil
}

