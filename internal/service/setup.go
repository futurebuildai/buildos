// ---------- Step 8: Complete ----------

// CompleteSetupInput is the final-step payload. Idempotent: a repeat
// call returns the same completed-at, no error.
type CompleteSetupInput struct {
	OrgID   uuid.UUID
	UserSub string
}

// Complete flips onboarding_complete=true after verifying the minimum
// preconditions are met: company profile filled, at least one trade,
// at least one cost code, and a default working calendar. The HTTP
// handler in W3 surfaces missing-prereq errors as 422 SETUP_INCOMPLETE.
func (s *SetupService) Complete(ctx context.Context, in CompleteSetupInput) (models.CompanyProfile, error) {
	if in.OrgID == uuid.Nil {
		return models.CompanyProfile{}, fmt.Errorf("%w: org_id required", ErrInvalidInput)
	}

	var out models.CompanyProfile
	err := pgx.BeginTxFunc(ctx, s.pool, pgx.TxOptions{}, func(tx pgx.Tx) error {
		cp, err := s.store.GetCompanyProfile(ctx, tx, in.OrgID)
		if err != nil {
			return err
		}
		if cp.OnboardingComplete {
			// Idempotent: return the existing snapshot. No audit row
			// on a no-op to keep the trail clean.
			out = cp
			return nil
		}
		if cp.LegalName == nil || *cp.LegalName == "" {
			return fmt.Errorf("%w: company info incomplete (legal_name missing)", ErrInvalidInput)
		}
		trades, err := s.store.ListTradeCategories(ctx, tx, in.OrgID)
		if err != nil {
			return err
		}
		if len(trades) == 0 {
			return fmt.Errorf("%w: at least one trade required", ErrInvalidInput)
		}
		codes, err := s.store.ListCostCodes(ctx, tx, in.OrgID)
		if err != nil {
			return err
		}
		if len(codes) == 0 {
			return fmt.Errorf("%w: at least one cost code required", ErrInvalidInput)
		}
		if _, err := s.store.GetDefaultWorkingCalendar(ctx, tx, in.OrgID); err != nil {
			if errors.Is(err, store.ErrNotFound) {
				return fmt.Errorf("%w: a default working calendar is required", ErrInvalidInput)
			}
			return err
		}

		if err := s.store.CompleteOnboarding(ctx, tx, in.OrgID, s.now()); err != nil {
			return err
		}
		cp2, err := s.store.GetCompanyProfile(ctx, tx, in.OrgID)
		if err != nil {
			return err
		}
		out = cp2

		s.audit.Record(ctx, tx, AuditEntry{
			OrgID:        in.OrgID,
			UserSub:      in.UserSub,
			Action:       AuditActionSetupCompleted,
			ResourceType: AuditResourceOrganization,
			ResourceID:   in.OrgID,
		})
		return nil
	})
	if err != nil {
		return models.CompanyProfile{}, mapSetupStoreError(err)
	}
	return out, nil
}

// ---------- Bootstrap tokens ----------

// IssuedBootstrapToken is the result of IssueBootstrapToken — the
// caller MUST show Cleartext to the operator once and never again
// (e.g. write it into fork.yaml + a secret store). Only the hash
// landed in the DB.
type IssuedBootstrapToken struct {
	ID        uuid.UUID
	Cleartext string
	ExpiresAt time.Time
}

// IssueBootstrapToken mints a one-shot owner-claim token. The
// cleartext is 32 random bytes base64url-encoded (43 chars); the
// sha256 hash lands in setup_bootstrap_tokens. TTL=0 falls back to
// DefaultBootstrapTokenTTL.
//
// Idempotency: this method does NOT collapse against an existing
// active token — the caller is expected to use the same secret-store
// file (and skip the call entirely if it already exists). Re-issuing
// produces a second active token; the redemption path accepts either
// until one is consumed.
func (s *SetupService) IssueBootstrapToken(ctx context.Context, orgID uuid.UUID, userSub string, ttl time.Duration) (IssuedBootstrapToken, error) {
	if orgID == uuid.Nil {
		return IssuedBootstrapToken{}, fmt.Errorf("%w: org_id required", ErrInvalidInput)
	}
	if ttl <= 0 {
		ttl = DefaultBootstrapTokenTTL
	}

	cleartext, err := generateBootstrapTokenCleartext()
	if err != nil {
		return IssuedBootstrapToken{}, fmt.Errorf("generate bootstrap token: %w", err)
	}
	hash := hashBootstrapToken(cleartext)
	expires := s.now().Add(ttl)

	var id uuid.UUID
	err = pgx.BeginTxFunc(ctx, s.pool, pgx.TxOptions{}, func(tx pgx.Tx) error {
		// Refuse to mint a bootstrap token for an org whose wizard
		// is already complete — the token would have no purpose and
		// just expand the attack surface.
		cp, gerr := s.store.GetCompanyProfile(ctx, tx, orgID)
		if gerr != nil {
			return gerr
		}
		if cp.OnboardingComplete {
			return ErrSetupAlreadyComplete
		}

		var qErr error
		id, qErr = s.store.CreateBootstrapToken(ctx, tx, store.CreateBootstrapTokenParams{
			OrgID:     orgID,
			TokenHash: hash,
			ExpiresAt: expires,
		})
		if qErr != nil {
			return qErr
		}
		s.audit.Record(ctx, tx, AuditEntry{
			OrgID:        orgID,
			UserSub:      userSub,
			Action:       AuditActionSetupBootstrapIssue,
			ResourceType: AuditResourceOrganization,
			ResourceID:   id,
		})
		return nil
	})
	if err != nil {
		return IssuedBootstrapToken{}, mapSetupStoreError(err)
	}
	return IssuedBootstrapToken{ID: id, Cleartext: cleartext, ExpiresAt: expires}, nil
}

// RedeemedBootstrapToken is what RedeemBootstrapToken returns. The
// caller (HTTP handler in W3) uses OrgID to populate the request
// context for subsequent wizard calls in the same session.
type RedeemedBootstrapToken struct {
	ID    uuid.UUID
	OrgID uuid.UUID
}

// RedeemBootstrapToken validates a cleartext token + marks it
// redeemed. redeemerSub is recorded in setup_bootstrap_tokens.redeemed_by
// after being parsed as a UUID (the HTTP handler passes the JWT sub
// once Brain emits UUID subs; for now nil-sub is accepted and the
// row records redeemed_by=NULL, but the consistency CHECK forbids
// that — so callers MUST pass a non-nil UUID).
//
// Returns ErrInvalidBootstrapToken on any failure (missing, expired,
// already redeemed, hash mismatch). The error is intentionally
// uniform — distinguishing reasons leaks information to an attacker
// probing the endpoint.
func (s *SetupService) RedeemBootstrapToken(ctx context.Context, cleartext string, redeemerID uuid.UUID) (RedeemedBootstrapToken, error) {
	if cleartext == "" {
		return RedeemedBootstrapToken{}, ErrInvalidBootstrapToken
	}
	if redeemerID == uuid.Nil {
		return RedeemedBootstrapToken{}, fmt.Errorf("%w: redeemer required", ErrInvalidInput)
	}
	hash := hashBootstrapToken(cleartext)
	now := s.now()

	var out RedeemedBootstrapToken
	err := pgx.BeginTxFunc(ctx, s.pool, pgx.TxOptions{}, func(tx pgx.Tx) error {
		tok, err := s.store.GetActiveBootstrapTokenByHash(ctx, tx, hash, now)
		if err != nil {
			if errors.Is(err, store.ErrNotFound) {
				return ErrInvalidBootstrapToken
			}
			return err
		}
		if err := s.store.RedeemBootstrapToken(ctx, tx, tok.ID, redeemerID, now); err != nil {
			if errors.Is(err, store.ErrNotFound) {
				// Lost a race against a concurrent redeem.
				return ErrInvalidBootstrapToken
			}
			return err
		}
		out = RedeemedBootstrapToken{ID: tok.ID, OrgID: tok.OrgID}
		s.audit.Record(ctx, tx, AuditEntry{
			OrgID:        tok.OrgID,
			Action:       AuditActionSetupBootstrapClaim,
			ResourceType: AuditResourceOrganization,
			ResourceID:   tok.ID,
		})
		return nil
	})
	if err != nil {
		return RedeemedBootstrapToken{}, mapSetupStoreError(err)
	}
	return out, nil
}

// RedeemBootstrapTokenForSubject is the HTTP-facing wrapper around
// RedeemBootstrapToken. It resolves the caller's OIDC subject to a
// users.id via SetupStore.LookupUserIDBySubject, verifies the token
// belongs to the caller's org (so a cross-org user cannot burn another
// org's token), then redeems atomically.
//
// Failure semantics (matching the HTTP error mapping in W3):
//   - subject not in users          → ErrBootstrapUserNotProvisioned (412)
//   - token not found / expired     → ErrInvalidBootstrapToken (401)
//   - token belongs to a different org than the JWT claim
//     → ErrInvalidBootstrapToken (401; NOT consumed)
//   - any redeem-time race          → ErrInvalidBootstrapToken (401)
//
// callerOrgID must be the org_id claim on the redeemer's JWT — used
// for both the user-lookup scope and the cross-org safety check.
func (s *SetupService) RedeemBootstrapTokenForSubject(ctx context.Context, cleartext, subject string, callerOrgID uuid.UUID) (RedeemedBootstrapToken, error) {
	if cleartext == "" {
		return RedeemedBootstrapToken{}, ErrInvalidBootstrapToken
	}
	if callerOrgID == uuid.Nil {
		return RedeemedBootstrapToken{}, fmt.Errorf("%w: caller org_id required", ErrInvalidInput)
	}
	if subject == "" {
		return RedeemedBootstrapToken{}, fmt.Errorf("%w: subject required", ErrInvalidInput)
	}
	hash := hashBootstrapToken(cleartext)
	now := s.now()

	var out RedeemedBootstrapToken
	err := pgx.BeginTxFunc(ctx, s.pool, pgx.TxOptions{}, func(tx pgx.Tx) error {
		userID, err := s.store.LookupUserIDBySubject(ctx, tx, subject, callerOrgID)
		if err != nil {
			if errors.Is(err, store.ErrNotFound) {
				return ErrBootstrapUserNotProvisioned
			}
			return err
		}

		tok, err := s.store.GetActiveBootstrapTokenByHash(ctx, tx, hash, now)
		if err != nil {
			if errors.Is(err, store.ErrNotFound) {
				return ErrInvalidBootstrapToken
			}
			return err
		}
		// Cross-org safety: if the JWT claimer's org doesn't match
		// the token's org, refuse — and do NOT consume the token.
		// An attacker with a valid (different-org) JWT and a guessed
		// cleartext must not be able to burn a victim's token.
		if tok.OrgID != callerOrgID {
			return ErrInvalidBootstrapToken
		}
		if err := s.store.RedeemBootstrapToken(ctx, tx, tok.ID, userID, now); err != nil {
			if errors.Is(err, store.ErrNotFound) {
				return ErrInvalidBootstrapToken
			}
			return err
		}
		out = RedeemedBootstrapToken{ID: tok.ID, OrgID: tok.OrgID}
		s.audit.Record(ctx, tx, AuditEntry{
			OrgID:        tok.OrgID,
			UserSub:      subject,
			Action:       AuditActionSetupBootstrapClaim,
			ResourceType: AuditResourceOrganization,
			ResourceID:   tok.ID,
		})
		return nil
	})
	if err != nil {
		// Pass-through sentinel errors; only map storage-shaped ones.
		if errors.Is(err, ErrInvalidBootstrapToken) ||
			errors.Is(err, ErrBootstrapUserNotProvisioned) ||
			errors.Is(err, ErrInvalidInput) {
			return RedeemedBootstrapToken{}, err
		}
		return RedeemedBootstrapToken{}, mapSetupStoreError(err)
	}
	return out, nil
}

// SeedBootstrapTokenIfNeeded is the boot-time helper that lets
// cmd/server materialize a setup_bootstrap_tokens row from an
// operator-supplied cleartext (BUILDOS_BOOTSTRAP_TOKEN env). Idempotent
// — relies on the schema's UNIQUE(token_hash) constraint to swallow
// re-boot inserts of the same cleartext.
//
// Returns (false, nil) when no fork-zero org exists yet, when the
// fork-zero org has already finished onboarding, or when an active
// token already exists for the cleartext. Returns (true, nil) when a
// fresh row landed. Returns (false, err) on storage failure or on
// malformed cleartext (caught at boot so a bad env var fails fast).
//
// orgID may be uuid.Nil; when Nil the service picks the first
// onboarding-incomplete organization. The Nil-fallback exists because
// cmd/server doesn't always know the fork's org_id at boot — in
// single-tenant forks there is exactly one organizations row, freshly
// seeded by migration 010.
func (s *SetupService) SeedBootstrapTokenIfNeeded(ctx context.Context, cleartext string, orgID uuid.UUID, ttl time.Duration) (bool, error) {
	if cleartext == "" {
		return false, nil // not configured — silent no-op
	}
	// Format validation: base64url-no-pad of 32 bytes is exactly 43
	// chars. Catches operator typos at boot rather than at redeem.
	if l := len(cleartext); l != 43 {
		return false, fmt.Errorf("%w: cleartext bootstrap token must be 43 base64url chars (got %d)", ErrInvalidInput, l)
	}
	if _, err := base64.RawURLEncoding.DecodeString(cleartext); err != nil {
		return false, fmt.Errorf("%w: cleartext bootstrap token is not base64url: %v", ErrInvalidInput, err)
	}
	if ttl <= 0 {
		ttl = DefaultBootstrapTokenTTL
	}

	hash := hashBootstrapToken(cleartext)
	expires := s.now().Add(ttl)

	var seeded bool
	err := pgx.BeginTxFunc(ctx, s.pool, pgx.TxOptions{}, func(tx pgx.Tx) error {
		target := orgID
		if target == uuid.Nil {
			// Pick the first onboarding-incomplete org. Strict in
			// single-tenant forks (exactly one org row). For
			// multi-tenant variants the caller must pass orgID.
			err := tx.QueryRow(ctx, `
				SELECT id FROM organizations
				WHERE onboarding_complete = false
				ORDER BY created_at ASC
				LIMIT 1`).Scan(&target)
			if err != nil {
				if errors.Is(err, pgx.ErrNoRows) {
					// All orgs onboarded — nothing to seed.
					return nil
				}
				return fmt.Errorf("find fork-zero org: %w", err)
			}
		} else {
			cp, gerr := s.store.GetCompanyProfile(ctx, tx, target)
			if gerr != nil {
				return gerr
			}
			if cp.OnboardingComplete {
				return nil
			}
		}

		_, qErr := s.store.CreateBootstrapToken(ctx, tx, store.CreateBootstrapTokenParams{
			OrgID:     target,
			TokenHash: hash,
			ExpiresAt: expires,
		})
		if qErr != nil {
			// SQLSTATE 23505: token already exists — idempotent
			// re-boot. Not an error.
			var pgErr *pgconn.PgError
			if errors.As(qErr, &pgErr) && pgErr.Code == "23505" {
				return nil
			}
			return fmt.Errorf("seed bootstrap token: %w", qErr)
		}
		seeded = true
		s.audit.Record(ctx, tx, AuditEntry{
			OrgID:        target,
			UserSub:      "system:boot",
			Action:       AuditActionSetupBootstrapIssue,
			ResourceType: AuditResourceOrganization,
			ResourceID:   target,
		})
		return nil
	})
	if err != nil {
		if errors.Is(err, ErrInvalidInput) {
			return false, err
		}
		return false, mapSetupStoreError(err)
	}
	return seeded, nil
}

// IsOnboardingComplete is a cheap read-only check used by the
// SetupGate middleware on every operational request. Single-row
// SELECT on a primary key, no tx overhead — pgx.Pool.QueryRow is
// fine here.
func (s *SetupService) IsOnboardingComplete(ctx context.Context, orgID uuid.UUID) (bool, error) {
	if orgID == uuid.Nil {
		return false, fmt.Errorf("%w: org_id required", ErrInvalidInput)
	}
	var done bool
	err := s.pool.QueryRow(ctx, `SELECT onboarding_complete FROM organizations WHERE id = $1`, orgID).Scan(&done)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return false, store.ErrNotFound
		}
		return false, fmt.Errorf("read onboarding state: %w", err)
	}
	return done, nil
}

