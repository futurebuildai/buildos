// ---------- Step 5: Working calendar ----------

// CreateCalendarInput is the wizard step-5 calendar payload. Holidays
// are submitted in the same step but inserted in a separate (atomic)
// call after the calendar row is created.
type CreateCalendarInput struct {
	OrgID            uuid.UUID
	UserSub          string
	Name             string
	Timezone         string
	WorkingDaysMask  int16
	DailyWorkMinutes int
	IsDefault        bool
}

// CreateCalendar inserts a working_calendars row. Timezone is
// validated as a real IANA TZ via time.LoadLocation — catches typos
// (e.g. "America/Hartford" vs "America/New_York") before the CPM
// engine fails to load it at recalc time.
func (s *SetupService) CreateCalendar(ctx context.Context, in CreateCalendarInput) (models.WorkingCalendar, error) {
	in.Name = strings.TrimSpace(in.Name)
	in.Timezone = strings.TrimSpace(in.Timezone)
	if in.OrgID == uuid.Nil {
		return models.WorkingCalendar{}, fmt.Errorf("%w: org_id required", ErrInvalidInput)
	}
	if in.Name == "" {
		return models.WorkingCalendar{}, fmt.Errorf("%w: name required", ErrInvalidInput)
	}
	if in.Timezone == "" {
		in.Timezone = "America/New_York" // schema default
	}
	if _, err := time.LoadLocation(in.Timezone); err != nil {
		return models.WorkingCalendar{}, fmt.Errorf("%w: timezone %q is not a valid IANA TZ", ErrInvalidInput, in.Timezone)
	}
	if in.WorkingDaysMask < 0 || in.WorkingDaysMask > 127 {
		return models.WorkingCalendar{}, fmt.Errorf("%w: working_days_mask must be 0..127", ErrInvalidInput)
	}
	if in.WorkingDaysMask == 0 {
		in.WorkingDaysMask = models.WorkingDaysMonFri
	}
	if in.DailyWorkMinutes <= 0 {
		in.DailyWorkMinutes = 480
	}
	if in.DailyWorkMinutes > 1440 {
		return models.WorkingCalendar{}, fmt.Errorf("%w: daily_work_minutes must be 1..1440", ErrInvalidInput)
	}

	var out models.WorkingCalendar
	err := pgx.BeginTxFunc(ctx, s.pool, pgx.TxOptions{}, func(tx pgx.Tx) error {
		if err := s.guardNotComplete(ctx, tx, in.OrgID); err != nil {
			return err
		}
		c, err := s.store.CreateWorkingCalendar(ctx, tx, store.CreateWorkingCalendarParams{
			OrgID:            in.OrgID,
			Name:             in.Name,
			Timezone:         in.Timezone,
			WorkingDaysMask:  in.WorkingDaysMask,
			DailyWorkMinutes: in.DailyWorkMinutes,
			IsDefault:        in.IsDefault,
		})
		if err != nil {
			return err
		}
		out = c
		s.audit.Record(ctx, tx, AuditEntry{
			OrgID:        in.OrgID,
			UserSub:      in.UserSub,
			Action:       AuditActionSetupCalendar,
			ResourceType: AuditResourceOrganization,
			ResourceID:   c.ID,
		})
		return nil
	})
	if err != nil {
		return models.WorkingCalendar{}, mapSetupStoreError(err)
	}
	return out, nil
}

// AddHolidayInput is the per-holiday payload. Multiple holidays go in
// separate AddHoliday calls so per-row UNIQUE collisions are diagnosed
// individually.
type AddHolidayInput struct {
	OrgID       uuid.UUID
	UserSub     string
	CalendarID  uuid.UUID
	HolidayDate time.Time
	Name        string
}

// AddHoliday inserts a holiday override. HolidayDate is truncated to
// UTC midnight before insert (schema column is DATE; truncating here
// keeps the audit-log row aligned with what landed in DB).
func (s *SetupService) AddHoliday(ctx context.Context, in AddHolidayInput) (models.HolidayOverride, error) {
	in.Name = strings.TrimSpace(in.Name)
	if in.OrgID == uuid.Nil || in.CalendarID == uuid.Nil {
		return models.HolidayOverride{}, fmt.Errorf("%w: org_id and calendar_id required", ErrInvalidInput)
	}
	if in.Name == "" {
		return models.HolidayOverride{}, fmt.Errorf("%w: name required", ErrInvalidInput)
	}
	if in.HolidayDate.IsZero() {
		return models.HolidayOverride{}, fmt.Errorf("%w: holiday_date required", ErrInvalidInput)
	}
	// Truncate to UTC midnight — DATE columns store calendar days.
	in.HolidayDate = time.Date(in.HolidayDate.Year(), in.HolidayDate.Month(), in.HolidayDate.Day(), 0, 0, 0, 0, time.UTC)

	var out models.HolidayOverride
	err := pgx.BeginTxFunc(ctx, s.pool, pgx.TxOptions{}, func(tx pgx.Tx) error {
		if err := s.guardNotComplete(ctx, tx, in.OrgID); err != nil {
			return err
		}
		h, err := s.store.CreateHolidayOverride(ctx, tx, store.CreateHolidayOverrideParams{
			CalendarID:  in.CalendarID,
			OrgID:       in.OrgID,
			HolidayDate: in.HolidayDate,
			Name:        in.Name,
		})
		if err != nil {
			return err
		}
		out = h
		s.audit.Record(ctx, tx, AuditEntry{
			OrgID:        in.OrgID,
			UserSub:      in.UserSub,
			Action:       AuditActionSetupHoliday,
			ResourceType: AuditResourceOrganization,
			ResourceID:   h.ID,
		})
		return nil
	})
	if err != nil {
		return models.HolidayOverride{}, mapSetupStoreError(err)
	}
	return out, nil
}

