// guardNotComplete short-circuits any wizard mutation once the org
// has flipped onboarding_complete=true. Defense against a stale UI
// re-submitting steps after completion.
func (s *SetupService) guardNotComplete(ctx context.Context, tx pgx.Tx, orgID uuid.UUID) error {
	cp, err := s.store.GetCompanyProfile(ctx, tx, orgID)
	if err != nil {
		return err
	}
	if cp.OnboardingComplete {
		return ErrSetupAlreadyComplete
	}
	return nil
}

// mapSetupStoreError translates pgx unique-violation (SQLSTATE 23505)
// into ErrInvalidInput so the HTTP handler maps to 409 / 422 rather
// than 500. Falls through to the package-shared mapStoreError for
// other cases (store.ErrNotFound → ErrNotFound).
func mapSetupStoreError(err error) error {
	if err == nil {
		return nil
	}
	var pgErr *pgconn.PgError
	if errors.As(err, &pgErr) && pgErr.Code == "23505" {
		return fmt.Errorf("%w: %s", ErrInvalidInput, pgErr.ConstraintName)
	}
	return mapStoreError(err)
}

// atLeastOneNonNil returns true when at least one pointer is non-nil.
// Used in PATCH-style validators where every field is optional but
// the call must mutate something.
func atLeastOneNonNil(ps ...*string) bool {
	for _, p := range ps {
		if p != nil {
			return true
		}
	}
	return false
}

// looksLikeRegion accepts a relaxed ISO-3166-2 shape: 2..3 letters,
// optional "-", 2..3 letters/digits. Not a hard validator; the goal
// is to catch obvious typos at wizard time. The CPM physics engine
// doesn't parse this — it's an informational metadata field.
func looksLikeRegion(s string) bool {
	if len(s) < 2 || len(s) > 8 {
		return false
	}
	for _, r := range s {
		if !(r == '-' || (r >= 'A' && r <= 'Z') || (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9')) {
			return false
		}
	}
	return true
}

// isShortCode validates trade-category codes — alphanumeric +
// underscore/hyphen, length in [min, max].
func isShortCode(s string, min, max int) bool {
	if len(s) < min || len(s) > max {
		return false
	}
	for _, r := range s {
		if !(r == '_' || r == '-' || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9')) {
			return false
		}
	}
	return true
}

// looksLikeCSICode accepts the CSI MasterFormat shape: two-digit
// segments separated by hyphens, 2..3 segments total (e.g. "03-30"
// or "03-30-00"). Strict enough to catch typos, loose enough to
// allow the parent-level codes the wizard seeds.
func looksLikeCSICode(s string) bool {
	parts := strings.Split(s, "-")
	if len(parts) < 2 || len(parts) > 3 {
		return false
	}
	for _, p := range parts {
		if len(p) != 2 {
			return false
		}
		for _, r := range p {
			if r < '0' || r > '9' {
				return false
			}
		}
	}
	return true
}

// generateBootstrapTokenCleartext returns 32 random bytes encoded as
// base64url-no-pad (43 chars). The encoding is URL-safe so operators
// can paste the token into a curl command without quote-escaping.
func generateBootstrapTokenCleartext() (string, error) {
	buf := make([]byte, bootstrapTokenByteLen)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(buf), nil
}

// hashBootstrapToken returns the hex-encoded sha256 hash of cleartext.
// Deterministic so setup_bootstrap_tokens.token_hash supports unique-
// index lookup; cryptographically sufficient because cleartext has
// 256 bits of CSPRNG entropy — no offline crack is feasible.
func hashBootstrapToken(cleartext string) string {
	sum := sha256.Sum256([]byte(cleartext))
	const hex = "0123456789abcdef"
	out := make([]byte, len(sum)*2)
	for i, b := range sum {
		out[i*2] = hex[b>>4]
		out[i*2+1] = hex[b&0x0f]
	}
	return string(out)
}
