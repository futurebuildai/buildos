// Setup-specific sentinel errors. Handlers map to HTTP codes:
//
//	ErrSetupAlreadyComplete → 409 SETUP_ALREADY_COMPLETE
//	ErrInvalidBootstrapToken → 401 INVALID_BOOTSTRAP_TOKEN
//	ErrBootstrapTokenExpired → 401 BOOTSTRAP_TOKEN_EXPIRED (same code as invalid for security)
//
// Reuses ErrNotFound, ErrInvalidInput from budget.go (same package).
var (
	ErrSetupAlreadyComplete        = errors.New("setup: onboarding already complete")
	ErrInvalidBootstrapToken       = errors.New("setup: invalid bootstrap token")
	ErrBootstrapUserNotProvisioned = errors.New("setup: bootstrap redeemer not yet provisioned in users table")
)

// Setup audit-log resource type / action constants. Wizard rows are
// not first-class business objects, so the resource_type uses the
// org_id (single subject per wizard run) and the action namespace
// captures which step landed. Lets `/audit?action_prefix=setup.`
// reconstruct the full wizard flow per org.
const (
	AuditResourceOrganization = "organization"

	AuditActionSetupCompanyInfo    = "setup.company_info.updated"
	AuditActionSetupTrade          = "setup.trade.created"
	AuditActionSetupCostCode       = "setup.cost_code.created"
	AuditActionSetupCalendar       = "setup.calendar.created"
	AuditActionSetupHoliday        = "setup.holiday.created"
	AuditActionSetupJurisdiction   = "setup.jurisdiction.created"
	AuditActionSetupCompleted      = "setup.completed"
	AuditActionSetupBootstrapIssue = "setup.bootstrap_token.issued"
	AuditActionSetupBootstrapClaim = "setup.bootstrap_token.redeemed"
)

// bootstrapTokenByteLen is the cleartext length for a newly-issued
// bootstrap token. 32 bytes (256 bits) from crypto/rand puts the
// cleartext well beyond any feasible brute-force budget even against
// a deterministic (sha256) hash — the security comes from the
// entropy of the input, not the cost of the hash.
const bootstrapTokenByteLen = 32

// DefaultBootstrapTokenTTL is the default lifetime applied when
// IssueBootstrapToken is called without an explicit expiry. Short
// enough that a leaked token in a fork-init artifact loses value
// before an attacker can discover the fork's URL and Brain JWKS;
// long enough that a slow first-admin claim doesn't have to race
// the clock.
const DefaultBootstrapTokenTTL = 7 * 24 * time.Hour

// SetupService orchestrates the embedded onboarding wizard (MB-7).
// One wizard run per fork — every method is scoped by org_id and the
// service uses the same single tx-per-mutation pattern as the other
// service-layer types (audit + write commit together).
//
// Bootstrap-token note: the cleartext token is generated by
// IssueBootstrapToken and shown ONCE to the caller (cmd/buildos-fork-init
// in W2 / operator scripts in W3+). Only the sha256 hash lands in
// setup_bootstrap_tokens. A 256-bit random cleartext makes the
// preimage space large enough that no offline crack is possible
// against a deterministic hash, and the deterministic hash is what
// lets the redemption path do a direct unique-index lookup. argon2id
// would force a full table scan on redemption with no security gain.
type SetupService struct {
	pool  *pgxpool.Pool
	store *store.SetupStore
	audit AuditRecorder
	now   func() time.Time
}

// NewSetupService creates a setup service bound to a pool + store.
// audit may be nil; nil falls back to a no-op recorder. clock may be
// nil; nil uses time.Now (tests inject a deterministic clock).
func NewSetupService(pool *pgxpool.Pool, s *store.SetupStore, audit AuditRecorder, clock func() time.Time) *SetupService {
	if audit == nil {
		audit = NewNoopAuditRecorder()
	}
	if clock == nil {
		clock = time.Now
	}
	return &SetupService{pool: pool, store: s, audit: audit, now: clock}
}

// ---------- State (wizard read) ----------

// SetupState is the GET /setup/state response shape. Each section is
// either nil (step not done) or populated. The wizard UI uses the
// presence/absence of each section to decide which step to land on.
type SetupState struct {
	OrgID               uuid.UUID
	OnboardingComplete  bool
	CompanyProfile      models.CompanyProfile
	Trades              []models.TradeCategory
	CostCodes           []models.CostCode
	DefaultCalendar     *models.WorkingCalendar
	DefaultHolidays     []models.HolidayOverride
	PermitJurisdictions []models.PermitJurisdiction
}

// GetState returns a consistent snapshot of the wizard's progress.
// Reads under a single read-only tx so partial-progress states are
// internally consistent (wizard UI never sees half a step).
func (s *SetupService) GetState(ctx context.Context, orgID uuid.UUID) (SetupState, error) {
	if orgID == uuid.Nil {
		return SetupState{}, fmt.Errorf("%w: org_id required", ErrInvalidInput)
	}
	var out SetupState
	out.OrgID = orgID
	err := pgx.BeginTxFunc(ctx, s.pool, pgx.TxOptions{AccessMode: pgx.ReadOnly}, func(tx pgx.Tx) error {
		cp, err := s.store.GetCompanyProfile(ctx, tx, orgID)
		if err != nil {
			return err
		}
		out.CompanyProfile = cp
		out.OnboardingComplete = cp.OnboardingComplete

		trades, err := s.store.ListTradeCategories(ctx, tx, orgID)
		if err != nil {
			return err
		}
		out.Trades = trades

		costs, err := s.store.ListCostCodes(ctx, tx, orgID)
		if err != nil {
			return err
		}
		out.CostCodes = costs

		cal, err := s.store.GetDefaultWorkingCalendar(ctx, tx, orgID)
		if err == nil {
			out.DefaultCalendar = &cal
			hols, herr := s.store.ListHolidaysForCalendar(ctx, tx, cal.ID)
			if herr != nil {
				return herr
			}
			out.DefaultHolidays = hols
		} else if !errors.Is(err, store.ErrNotFound) {
			return err
		}

		juris, err := s.store.ListPermitJurisdictions(ctx, tx, orgID)
		if err != nil {
			return err
		}
		out.PermitJurisdictions = juris
		return nil
	})
	if err != nil {
		return SetupState{}, mapSetupStoreError(err)
	}
	return out, nil
}

// ---------- Step 1: Company info ----------

// UpdateCompanyInfoInput is the wizard step-1 payload. Fields are
// pointers so the caller can patch a subset without clobbering prior
// submissions.
type UpdateCompanyInfoInput struct {
	OrgID       uuid.UUID
	UserSub     string
	LegalName   *string
	Address     *string
	EIN         *string
	CompanyType *string
	Region      *string
}

// UpdateCompanyInfo writes the company-profile fields. The audit row
// records the patch (only fields the caller submitted) so the wizard
// trail shows step-by-step diffs rather than the full snapshot.
func (s *SetupService) UpdateCompanyInfo(ctx context.Context, in UpdateCompanyInfoInput) (models.CompanyProfile, error) {
	if in.OrgID == uuid.Nil {
		return models.CompanyProfile{}, fmt.Errorf("%w: org_id required", ErrInvalidInput)
	}
	if !atLeastOneNonNil(in.LegalName, in.Address, in.EIN, in.CompanyType, in.Region) {
		return models.CompanyProfile{}, fmt.Errorf("%w: at least one field required", ErrInvalidInput)
	}
	if in.Region != nil && !looksLikeRegion(*in.Region) {
		return models.CompanyProfile{}, fmt.Errorf("%w: region must look like ISO-3166-2 (e.g. US-CT)", ErrInvalidInput)
	}

	var out models.CompanyProfile
	err := pgx.BeginTxFunc(ctx, s.pool, pgx.TxOptions{}, func(tx pgx.Tx) error {
		if err := s.guardNotComplete(ctx, tx, in.OrgID); err != nil {
			return err
		}
		if err := s.store.UpdateCompanyProfile(ctx, tx, store.UpdateCompanyProfileParams{
			OrgID:       in.OrgID,
			LegalName:   in.LegalName,
			Address:     in.Address,
			EIN:         in.EIN,
			CompanyType: in.CompanyType,
			Region:      in.Region,
		}); err != nil {
			return err
		}
		cp, err := s.store.GetCompanyProfile(ctx, tx, in.OrgID)
		if err != nil {
			return err
		}
		out = cp

		patch, _ := json.Marshal(map[string]any{
			"legal_name":   in.LegalName,
			"address":      in.Address,
			"ein":          in.EIN,
			"company_type": in.CompanyType,
			"region":       in.Region,
		})
		s.audit.Record(ctx, tx, AuditEntry{
			OrgID:        in.OrgID,
			UserSub:      in.UserSub,
			Action:       AuditActionSetupCompanyInfo,
			ResourceType: AuditResourceOrganization,
			ResourceID:   in.OrgID,
			After:        patch,
		})
		return nil
	})
	if err != nil {
		return models.CompanyProfile{}, mapSetupStoreError(err)
	}
	return out, nil
}

// ---------- Step 3: Trades ----------

// CreateTradeInput is the wizard step-3 single-trade payload. Step 3
// is bulk-friendly (the wizard typically submits an array); the
// service exposes the single-row method so per-row failures (e.g.
// UNIQUE collision on code) surface individually.
type CreateTradeInput struct {
	OrgID       uuid.UUID
	UserSub     string
	Code        string
	Name        string
	Description *string
	IsDefault   bool
}

// CreateTrade inserts a trade category. Code is normalized (upper +
// trimmed) so the operator can paste "  elec " and land "ELEC". Codes
// are required to be 1..16 ASCII chars after normalization.
func (s *SetupService) CreateTrade(ctx context.Context, in CreateTradeInput) (models.TradeCategory, error) {
	in.Code = strings.ToUpper(strings.TrimSpace(in.Code))
	in.Name = strings.TrimSpace(in.Name)
	if in.OrgID == uuid.Nil {
		return models.TradeCategory{}, fmt.Errorf("%w: org_id required", ErrInvalidInput)
	}
	if !isShortCode(in.Code, 1, 16) {
		return models.TradeCategory{}, fmt.Errorf("%w: code must be 1..16 ASCII chars (A-Z, 0-9, _, -)", ErrInvalidInput)
	}
	if in.Name == "" {
		return models.TradeCategory{}, fmt.Errorf("%w: name required", ErrInvalidInput)
	}

	var out models.TradeCategory
	err := pgx.BeginTxFunc(ctx, s.pool, pgx.TxOptions{}, func(tx pgx.Tx) error {
		if err := s.guardNotComplete(ctx, tx, in.OrgID); err != nil {
			return err
		}
		t, err := s.store.CreateTradeCategory(ctx, tx, store.CreateTradeCategoryParams{
			OrgID:       in.OrgID,
			Code:        in.Code,
			Name:        in.Name,
			Description: in.Description,
			IsDefault:   in.IsDefault,
		})
		if err != nil {
			return err
		}
		out = t
		s.audit.Record(ctx, tx, AuditEntry{
			OrgID:        in.OrgID,
			UserSub:      in.UserSub,
			Action:       AuditActionSetupTrade,
			ResourceType: AuditResourceOrganization,
			ResourceID:   t.ID,
		})
		return nil
	})
	if err != nil {
		return models.TradeCategory{}, mapSetupStoreError(err)
	}
	return out, nil
}

